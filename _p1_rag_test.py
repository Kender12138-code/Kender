# 我们期望命中的是"第五段 常见问题"里的票据遗失说明
TARGET_KEYWORD = "票据遗失"


def recall_hit(chunks):
    return any(TARGET_KEYWORD in c for c in chunks)


def search(queries, k=3):
    """按多条语句检索并合并去重（与 retrieve_document 内部逻辑一致）。"""
    merged, seen, used = [], set(), []
    for q in queries:
        for c in retrieve(q, k=k, index_dir=TEST_INDEX_DIR):
            key = c[:80]
            if key not in seen:
                seen.add(key)
                merged.append(c)
                used.append(q)
    return merged, used


async def main():
    n = build_index(DOC, index_dir=TEST_INDEX_DIR)
    total = chunk_count(index_dir=TEST_INDEX_DIR)
    print(f"测试索引：{n} 个片段（独立目录，未动你 data/ 下的真实索引）")
    print(f"改写启用阈值：REWRITE_MIN_CHUNKS = {REWRITE_MIN_CHUNKS}")
    print(f"当前索引 {total} 个片段 -> "
          f"{'启用' if total >= REWRITE_MIN_CHUNKS else '跳过'} query 改写\n")

    query = "发票弄丢了要咋整"
    print(f"口语化问题：{query}")
    print(f"目标：命中含「{TARGET_KEYWORD}」的片段\n")

    base, _ = search([query])
    print(f"A. 只用原始问题：命中 = {recall_hit(base)}")

    expanded = await expand_query(query)
    print(f"\nB. query 改写结果：{expanded}")
    merged, used = search([query] + [x for x in expanded if x != query])
    print(f"   合并去重后命中 = {recall_hit(merged)}，共 {len(merged)} 条片段")
    for i, c in enumerate(merged, 1):
        mark = " <== 目标" if TARGET_KEYWORD in c else ""
        print(f"   [{i}] {c.strip()[:42]}…{mark}")
    print("\n结论：小语料下原始问题已能命中，改写增益不明显 —— 这正是"
          "加规模阈值的原因（省掉一次 LLM 调用）。")


if __name__ == "__main__":
    asyncio.run(main())
